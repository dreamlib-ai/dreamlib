"""Writes frontend/src/generated/api.ts from the backend's OpenAPI schema (S3). No packages beyond the backend's.

    backend/.venv/Scripts/python scripts/gen_client.py          # write
    backend/.venv/Scripts/python scripts/gen_client.py --check  # exit 1 when the file is out of date

Every /api/v1 operation becomes one function named after its route function (camelCase) that calls
`request` from frontend/src/http.ts; every schema those operations reach becomes a type. Operations marked
`x-raw-body` (audio upload) are left to frontend/src/api.ts. backend/tests/test_client_generated.py runs --check."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "src" / "generated" / "api.ts"
HEADER = "// Generated by scripts/gen_client.py from the backend OpenAPI schema. Do not edit; rerun the script.\n"


def load_spec() -> dict:
    sys.path.insert(0, str(ROOT / "backend"))
    from app.main import create_app
    from app.services import Services

    return create_app(Services()).openapi()


def type_name(ref_or_name: str) -> str:
    name = ref_or_name.rsplit("/", 1)[-1]  # Panel-Output -> PanelOutput
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", name))


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def ts(schema: dict, refs: set[str]) -> str:
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[1]
        refs.add(name)
        return type_name(name)
    if "anyOf" in schema or "oneOf" in schema:
        parts = [ts(s, refs) for s in schema.get("anyOf") or schema["oneOf"]]
        return " | ".join(dict.fromkeys(parts))
    if "enum" in schema:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        inner = ts(schema.get("items", {}), refs)
        return f"Array<{inner}>" if " " in inner else f"{inner}[]"
    if kind == "object" or "properties" in schema:
        props = schema.get("properties", {})
        if not props:
            extra = schema.get("additionalProperties")
            return f"Record<string, {ts(extra, refs) if isinstance(extra, dict) else 'unknown'}>"
        required = set(schema.get("required", []))
        fields = [f"{k}{'' if k in required else '?'}: {ts(v, refs)}" for k, v in props.items()]
        return "{ " + "; ".join(fields) + " }"
    return "unknown"


def operations(spec: dict, refs: set[str]) -> list[str]:
    out = []
    for path, ops in spec["paths"].items():
        if not path.startswith("/api/v1/"):
            continue
        for method, op in ops.items():
            if op.get("x-raw-body"):
                continue
            name = camel(op["operationId"])
            args, query = [], []
            url = path
            for p in op.get("parameters", []):
                t = ts(p.get("schema", {}), refs)
                if p["in"] == "path":
                    arg = camel(p["name"])
                    args.append(f"{arg}: {t}")
                    url = url.replace("{" + p["name"] + "}", "${encodeURIComponent(String(" + arg + "))}")
                elif p["in"] == "query":
                    query.append(f"{p['name']}?: {t}")
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            if body:
                args.append(f"body: {ts(body, refs)}")
            if query:
                args.append("query: { " + "; ".join(query) + " } = {}")
            args.append("signal?: AbortSignal")
            ok = next((v for k, v in op["responses"].items() if k.startswith("2")), {})
            schema = ok.get("content", {}).get("application/json", {}).get("schema")
            result = ts(schema, refs) if schema else "void"
            target = f"`{url}" + ("${search(query)}" if query else "") + "`"
            out.append(f"/** {method.upper()} {path} */\n"
                       f"export const {name} = ({', '.join(args)}) =>\n"
                       f"  request<{result}>('{method.upper()}', {target}, {'body' if body else 'undefined'}, signal);\n")
    return out


def render(spec: dict) -> str:
    refs: set[str] = set()
    ops = operations(spec, refs)
    schemas = spec["components"]["schemas"]
    types: dict[str, str] = {}
    while refs - types.keys():
        for name in sorted(refs - types.keys()):
            s = schemas[name]
            doc = (s.get("description") or "").strip().split("\n")[0]
            types[name] = (f"/** {doc} */\n" if doc else "") + f"export type {type_name(name)} = {ts(s, refs)};\n"
    helper = ("const search = (query: Record<string, unknown>) => {\n"
              "  const params = new URLSearchParams();\n"
              "  for (const [k, v] of Object.entries(query)) if (v !== undefined && v !== null) params.set(k, String(v));\n"
              "  const text = params.toString();\n"
              "  return text ? `?${text}` : '';\n"
              "};\n")
    uses_query = any("search(query)" in o for o in ops)
    return (HEADER + "import { request } from '../http';\n\n" + "\n".join(types[k] for k in sorted(types)) + "\n"
            + (helper + "\n" if uses_query else "") + "\n".join(ops))


def main() -> int:
    text = render(load_spec())
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run scripts/gen_client.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
